    private void carregarTabela() {
        try {
            modelo.setRowCount(0);
            ArrayList<Categoria> lista = controller.listar();
            for (Categoria c : lista) {
                modelo.addRow(new Object[]{c.getIdCategoria(), c.getNome(), c.getDescricao()});
            }
            Estilo.ajustarColunas(tabela);
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Erro", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void limpar() {
        idSelecionado = 0;
        txtNome.setText("");
        txtDescricao.setText("");
        tabela.clearSelection();
        txtNome.requestFocus();
    }

    private void salvar() {
        try {
            if (idSelecionado == 0) {
                controller.inserir(0, txtNome.getText(), txtDescricao.getText());
                JOptionPane.showMessageDialog(this, "Categoria cadastrada com sucesso!");
            } else {
                controller.alterar(idSelecionado, txtNome.getText(), txtDescricao.getText());
                JOptionPane.showMessageDialog(this, "Categoria alterada com sucesso!");
            }
            carregarTabela();
            limpar();
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Atenção", JOptionPane.WARNING_MESSAGE);
        }
    }

    private void excluir() {
        if (idSelecionado == 0) {
            JOptionPane.showMessageDialog(this, "Selecione uma categoria na tabela para excluir.");
            return;
        }
        int resp = JOptionPane.showConfirmDialog(this, "Deseja realmente excluir esta categoria?",
                "Confirmar exclusão", JOptionPane.YES_NO_OPTION);
        if (resp != JOptionPane.YES_OPTION) {
            return;
        }
        try {
            controller.excluir(idSelecionado);
            JOptionPane.showMessageDialog(this, "Categoria excluída com sucesso!");
            carregarTabela();
            limpar();
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Não foi possível excluir", JOptionPane.WARNING_MESSAGE);
        }
    }

