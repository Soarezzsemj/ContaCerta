    private void carregarCombos() {
        try {
            cbCategoria.setModel(new DefaultComboBoxModel<>(controller.listarCategorias().toArray(new Categoria[0])));
            cbFormaPagamento.setModel(new DefaultComboBoxModel<>(controller.listarFormasPagamento().toArray(new FormaPagamento[0])));
            cbConta.setModel(new DefaultComboBoxModel<>(controller.listarContas().toArray(new Conta[0])));
            cbEstabelecimento.setModel(new DefaultComboBoxModel<>(controller.listarEstabelecimentos().toArray(new Estabelecimento[0])));
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Erro", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void carregarTabela() {
        try {
            gastos = new ArrayList<>();
            modelo.setRowCount(0);
            gastos = controller.listar();
            for (Gasto g : gastos) {
                modelo.addRow(new Object[]{g.getIdGasto(), Formato.formatarData(g.getDataGasto()), g.getDescricao(),
                    Formato.formatarMoeda(g.getValor()), g.getNomeCategoria(), g.getNomeFormaPagamento(),
                    g.getNomeConta(), g.getNomeEstabelecimento()});
            }
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Erro", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void preencherCampos(Gasto g) {
        idSelecionado = g.getIdGasto();
        txtDescricao.setText(g.getDescricao());
        txtValor.setText(g.getValor().toPlainString().replace('.', ','));
        txtData.setText(Formato.formatarData(g.getDataGasto()));
        selecionarPorId(cbCategoria, Categoria::getIdCategoria, g.getIdCategoria());
        selecionarPorId(cbFormaPagamento, FormaPagamento::getIdFormaPagamento, g.getIdFormaPagamento());
        selecionarPorId(cbConta, Conta::getIdConta, g.getIdConta());
        selecionarPorId(cbEstabelecimento, Estabelecimento::getIdEstabelecimento, g.getIdEstabelecimento());
    }

    private <T> void selecionarPorId(JComboBox<T> combo, ToIntFunction<T> codigo, int id) {
        combo.setSelectedIndex(-1);
        for (int i = 0; i < combo.getItemCount(); i++) {
            if (codigo.applyAsInt(combo.getItemAt(i)) == id) {
                combo.setSelectedIndex(i);
                return;
            }
        }
    }

    private void limpar() {
        idSelecionado = 0;
        txtDescricao.setText("");
        txtValor.setText("");
        txtData.setText(Formato.formatarData(LocalDate.now()));
        cbCategoria.setSelectedIndex(-1);
        cbFormaPagamento.setSelectedIndex(-1);
        cbConta.setSelectedIndex(-1);
        cbEstabelecimento.setSelectedIndex(-1);
        tabela.clearSelection();
        txtDescricao.requestFocus();
    }

    private void salvar() {
        try {
            if (idSelecionado == 0) {
                controller.inserir(txtDescricao.getText(), txtValor.getText(), txtData.getText(),
                        (Categoria) cbCategoria.getSelectedItem(), (FormaPagamento) cbFormaPagamento.getSelectedItem(),
                        (Conta) cbConta.getSelectedItem(), (Estabelecimento) cbEstabelecimento.getSelectedItem());
                JOptionPane.showMessageDialog(this, "Gasto cadastrado com sucesso!");
            } else {
                controller.alterar(idSelecionado, txtDescricao.getText(), txtValor.getText(), txtData.getText(),
                        (Categoria) cbCategoria.getSelectedItem(), (FormaPagamento) cbFormaPagamento.getSelectedItem(),
                        (Conta) cbConta.getSelectedItem(), (Estabelecimento) cbEstabelecimento.getSelectedItem());
                JOptionPane.showMessageDialog(this, "Gasto alterado com sucesso!");
            }
            carregarTabela();
            limpar();
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Atenção", JOptionPane.WARNING_MESSAGE);
        }
    }

    private void excluir() {
        if (idSelecionado == 0) {
            JOptionPane.showMessageDialog(this, "Selecione um gasto na tabela para excluir.");
            return;
        }
        int resp = JOptionPane.showConfirmDialog(this, "Deseja realmente excluir este gasto?",
                "Confirmar exclusão", JOptionPane.YES_NO_OPTION);
        if (resp != JOptionPane.YES_OPTION) {
            return;
        }
        try {
            controller.excluir(idSelecionado);
            JOptionPane.showMessageDialog(this, "Gasto excluído com sucesso!");
            carregarTabela();
            limpar();
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Não foi possível excluir", JOptionPane.WARNING_MESSAGE);
        }
    }

